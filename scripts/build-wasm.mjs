// Compiles rust/ to WebAssembly and embeds it (base64) in src/engine/wasm.gen.ts, so the package
// ships as plain JS: no .wasm file to configure in a bundler. Skips quietly when Rust is missing.
import { execFileSync } from "node:child_process";
import { existsSync, readFileSync, writeFileSync, copyFileSync } from "node:fs";

const out = "rust/target/wasm32-unknown-unknown/release/perfscope_core.wasm";
try {
  execFileSync("cargo", ["build", "--release", "--target", "wasm32-unknown-unknown", "--manifest-path", "rust/Cargo.toml"], { stdio: "inherit" });
} catch {
  console.warn("[perfscope] cargo / wasm32 target not found: keeping the committed src/engine/wasm.gen.ts");
  process.exit(0);
}
if (existsSync(out)) {
  copyFileSync(out, "src/engine/core.wasm");
  const b64 = readFileSync(out).toString("base64");
  writeFileSync("src/engine/wasm.gen.ts", `// generated by scripts/build-wasm.mjs from rust/ : do not edit\nexport const WASM_BASE64 = "${b64}";\n`);
  console.log(`[perfscope] wasm embedded (${readFileSync(out).length} bytes)`);
}
